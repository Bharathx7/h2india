// The personal data inventory (step 12.2, DPDP): every table that holds personal data, which fields, why, how long,
// who can read it and which outside processor receives it. docs/privacy/inventory.md is written from this list
// (scripts/privacy-inventory.ts), and inventory.test.ts fails when a table isn't classified or a personal-looking
// column isn't listed, so a new column can't arrive without a decision.
//
// Retention is null where no period is decided yet (the founder and the lawyer decide; RETENTION in retention.ts runs
// nothing until they do). Processor names are the roles until vendors are chosen (M-items in docs/decisions.md).

export const PROCESSORS = {
  hosting: "Hosting provider (server, database, backups)",
  email: "Email provider",
  sms: "SMS provider",
  whatsapp: "WhatsApp provider",
  payments: "Payment partner",
  gstin: "GSTIN check provider",
} as const;
type Processor = keyof typeof PROCESSORS;

export interface PersonalTable {
  table: string;
  /** Columns that hold personal data (database names). */
  fields: string[];
  /** Columns that match the personal-data pattern but aren't personal here, with the reason in `note`. */
  notPersonal?: string[];
  purpose: string;
  /** The legal basis under the DPDP Act: consent, or a legitimate use (s.7). */
  basis: "Consent" | "Legitimate use: contract" | "Legitimate use: legal obligation" | "Legitimate use: security";
  /** How long, as decided; null when not decided yet. */
  retention: string | null;
  access: string;
  processors: Processor[];
  note?: string;
}

