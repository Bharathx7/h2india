// Prints the SQL that seeds roles and permissions from src/authz/catalogue.ts (step 3.4).
// Usage: pnpm --filter @h2india/core exec tsx scripts/authz-seed.ts > ../db/migrations/0005_authz_seed.sql
// Run once per change to the catalogue, as a new migration; never edit an applied migration.
import {
  COMPANY_PERMISSIONS,
  OPERATOR_ACTIONS,
  OPERATOR_AREAS,
  OPERATOR_EXTRA,
  ROLES,
  SENSITIVE_AREAS,
} from "../src/authz/catalogue";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines: string[] = ["-- Generated by packages/core/scripts/authz-seed.ts from src/authz/catalogue.ts (step 3.4)."];

const perms: [string, string, string, boolean][] = [];
for (const [key, text] of Object.entries(COMPANY_PERMISSIONS)) {
  perms.push([key, "company", text, key === "payout_bank.change" || key === "team.manage"]);
}
for (const area of OPERATOR_AREAS) {
  for (const action of OPERATOR_ACTIONS) {
    perms.push([
      `${area}.${action}`,
      "operator",
      `${action} in ${area}`,
      (SENSITIVE_AREAS as readonly string[]).includes(area),
    ]);
  }
}
for (const [key, text] of Object.entries(OPERATOR_EXTRA)) perms.push([key, "operator", text, false]);

lines.push('INSERT INTO "core"."permissions" ("key", "layer", "description", "sensitive") VALUES');
lines.push(
  perms.map(([k, l, d, s]) => `  (${q(k)}, ${q(l)}, ${q(d)}, ${String(s)})`).join(",\n") +
    '\nON CONFLICT ("key") DO NOTHING;',
);
lines.push("--> statement-breakpoint");
lines.push('INSERT INTO "core"."roles" ("id", "scope", "name", "description") VALUES');
lines.push(
  ROLES.map((r) => `  (gen_random_uuid(), ${q(r.scope)}, ${q(r.name)}, ${q(r.description)})`).join(",\n") +
    '\nON CONFLICT ("scope", "name") DO NOTHING;',
);
for (const r of ROLES) {
  lines.push("--> statement-breakpoint");
  lines.push(
    `INSERT INTO "core"."role_permissions" ("role_id", "permission_key")\nSELECT r."id", p."key" FROM "core"."roles" r, "core"."permissions" p\nWHERE r."scope" = ${q(r.scope)} AND r."name" = ${q(r.name)} AND p."key" IN (${r.permissions.map(q).join(", ")})\nON CONFLICT DO NOTHING;`,
  );
}
// Step 3.3 stored owner/admin/member; step 3.4 uses the designed role names.
lines.push("--> statement-breakpoint");
lines.push(`UPDATE "core"."memberships" m SET "role" = 'Admin' WHERE m."role" IN ('owner', 'admin');`);
lines.push("--> statement-breakpoint");
lines.push(
  `UPDATE "core"."memberships" m SET "role" = CASE WHEN o."kind" = 'supplier' THEN 'Viewer' ELSE 'Requester' END\nFROM "core"."organisations" o WHERE o."id" = m."organisation_id" AND m."role" = 'member';`,
);
process.stdout.write(lines.join("\n") + "\n");
